let eventSeq = 0;
function nextEventId(): string {
  eventSeq += 1;
  return `le-${String(eventSeq).padStart(3, "0")}`;
}

function pairSuccess(
  userId: string,
  merchantId: string | null,
  at: Date,
  ip: string,
  device: string,
): LoginEvent[] {
  return [
    ev({
      id: nextEventId(),
      at,
      userId,
      merchantId,
      stage: "password",
      result: "success",
      reason: null,
      ip,
      device,
    }),
    ev({
      id: nextEventId(),
      at: addMs(at, 8_000),
      userId,
      merchantId,
      stage: "2fa",
      result: "success",
      reason: null,
      ip,
      device,
    }),
  ];
}

